"""Genera el DDL PostgreSQL del OLTP a partir del script T-SQL canónico.

Fuente: db/sqlserver/1_oltp_elestablo_v1.sql
Salida: db/postgres/oltp/01_oltp_schema.sql

No pretende ser un traductor T-SQL genérico: cubre exactamente las
construcciones que usa el esquema del proyecto. Si el esquema de origen cambia,
volver a ejecutarlo y revisar el diff.

Uso:  python db/postgres/tools/generate_oltp_schema.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "db" / "sqlserver" / "1_oltp_elestablo_v1.sql"
TARGET = ROOT / "db" / "postgres" / "oltp" / "01_oltp_schema.sql"

TABLE_RE = re.compile(r"CREATE TABLE dbo\.(\w+)\s*\((.*?)\n\s*\);", re.S)
INDEX_RE = re.compile(
    r"IF NOT EXISTS \(SELECT 1 FROM sys\.indexes WHERE name = '(\w+)'\)\s*"
    r"CREATE (UNIQUE )?INDEX (\w+)\s*ON dbo\.(\w+) \(([^)]*)\)"
    r"(?:\s*INCLUDE \(([^)]*)\))?"
    r"(?:\s*WHERE ([^;]+))?;",
    re.S,
)

COMPUTED_ACCESOS = """\
        es_contacto_utilizable boolean GENERATED ALWAYS AS (
            CASE
                WHEN fecha_envio_datos IS NOT NULL
                 AND telefono_es_valido
                 AND consentimiento_datos_otorgado
                THEN true
                ELSE false
            END
        ) STORED,"""


def convert_column_lines(body: str, table: str) -> str:
    # Columnas boolean (BIT) del origen: sus comparaciones con 0/1 se traducen.
    bool_cols = [
        m.group(1)
        for m in re.finditer(r"^\s*(\w+)\s+BIT\b", body, re.M | re.I)
    ]

    # Columnas calculadas: se reemplazan antes del mapeo de tipos.
    if table == "accesos_catalogo_web":
        body = re.sub(
            r"\n\s*es_contacto_utilizable AS \(.*?\) PERSISTED,",
            "\n" + COMPUTED_ACCESOS,
            body,
            flags=re.S,
        )
    body = body.replace(
        "subtotal AS (cantidad * precio_unitario),",
        "subtotal numeric GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,",
    )

    body = re.sub(r"\bINT IDENTITY\(1,\s*1\)", "integer GENERATED BY DEFAULT AS IDENTITY", body)
    body = re.sub(r"\bBIGINT IDENTITY\(1,\s*1\)", "bigint GENERATED BY DEFAULT AS IDENTITY", body)
    body = re.sub(r"\bUNIQUEIDENTIFIER\b", "uuid", body)
    body = re.sub(r"\bNVARCHAR\(MAX\)", "text", body, flags=re.I)
    body = re.sub(r"\bNVARCHAR", "varchar", body, flags=re.I)
    body = re.sub(r"\bDATETIME2\((\d+)\)", r"timestamp(\1)", body, flags=re.I)
    body = re.sub(r"\bDATETIME2\b", "timestamp(0)", body, flags=re.I)
    body = re.sub(r"\bDECIMAL\(", "numeric(", body, flags=re.I)
    body = re.sub(r"\bTINYINT\b", "smallint", body, flags=re.I)
    body = re.sub(r"\bBIGINT\b", "bigint", body, flags=re.I)
    body = re.sub(r"(?<![.\w])INT\b", "integer", body)
    body = re.sub(r"\)\s*\bBIT\b", ") boolean", body)  # no ocurre; defensivo

    # Booleanos y sus defaults, línea por línea.
    fixed_lines = []
    for line in body.splitlines():
        if re.search(r"\bBIT\b", line):
            line = re.sub(r"\bBIT\b", "boolean", line)
            line = re.sub(r"DEFAULT \(1\)", "DEFAULT true", line)
            line = re.sub(r"DEFAULT \(0\)", "DEFAULT false", line)
        fixed_lines.append(line)
    body = "\n".join(fixed_lines)

    body = re.sub(r"\bNEWID\(\)", "gen_random_uuid()", body)
    body = re.sub(r"\bSYSUTCDATETIME\(\)", "(now() AT TIME ZONE 'utc')", body)
    for col in bool_cols:
        body = re.sub(rf"\b{col}\s*=\s*1\b", f"{col} = true", body)
        body = re.sub(rf"\b{col}\s*=\s*0\b", f"{col} = false", body)
    body = body.replace("REFERENCES dbo.", "REFERENCES ")
    body = body.replace("dbo.", "")
    return body


def convert_tables(sql: str) -> tuple[str, list[str]]:
    blocks: list[str] = []
    names: list[str] = []
    for match in TABLE_RE.finditer(sql):
        table = match.group(1)
        names.append(table)
        body = convert_column_lines(match.group(2), table)
        blocks.append(f"CREATE TABLE IF NOT EXISTS {table} ({body}\n);")
    return "\n\n".join(blocks), names


def convert_indexes(sql: str) -> str:
    out = []
    for match in INDEX_RE.finditer(sql):
        _, unique, name, table, cols, include, where = match.groups()
        stmt = f"CREATE {'UNIQUE ' if unique else ''}INDEX IF NOT EXISTS {name}"
        stmt += f"\n    ON {table} ({cols.strip()})"
        if include:
            stmt += f"\n    INCLUDE ({include.strip()})"
        if where:
            predicate = " ".join(where.split())
            predicate = re.sub(r"= 1\b", "= true", predicate)
            predicate = re.sub(r"= 0\b", "= false", predicate)
            stmt += f"\n    WHERE {predicate}"
        out.append(stmt + ";")
    return "\n\n".join(out)


def main() -> None:
    sql = SOURCE.read_text(encoding="utf-8", errors="replace")
    tables, names = convert_tables(sql)
    indexes = convert_indexes(sql)
    header = f"""\
-- GENERADO por db/postgres/tools/generate_oltp_schema.py
-- Fuente: db/sqlserver/1_oltp_elestablo_v1.sql
-- Esquema transaccional canónico de Parrilladas El Establo.
--
-- Paridad con SQL Server: mismos nombres de tabla y columna, mismos CHECK y
-- FK. Fechas DATETIME2(0) UTC -> timestamp(0) sin zona (sempre UTC).
-- No editar a mano: cambiar el origen y regenerar.
--
-- Tablas: {len(names)}

SET client_min_messages = warning;

"""
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(header + tables + "\n\n-- Índices\n\n" + indexes + "\n", encoding="utf-8")
    print(f"generado {TARGET} ({len(names)} tablas, {len(INDEX_RE.findall(sql))} índices)")


if __name__ == "__main__":
    main()
