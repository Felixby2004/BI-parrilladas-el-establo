            tipo_consumo IS NULL OR tipo_consumo = 'SALON'
        ),
        CONSTRAINT CK_pedidos_estado CHECK (estado_pedido IN (
            'PENDIENTE', 'EN_PREPARACION', 'ENTREGADO', 'CANCELADO'
        )),
        CONSTRAINT CK_pedidos_total CHECK (total >= 0)
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
        id_detalle bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        id_pedido uuid NOT NULL,
        id_producto integer NOT NULL,
        cantidad integer NOT NULL,
        precio_unitario numeric(10,2) NOT NULL,

        subtotal numeric GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,

        CONSTRAINT PK_detalle_pedido PRIMARY KEY (id_detalle),
        CONSTRAINT FK_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
        CONSTRAINT FK_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
        CONSTRAINT CK_detalle_pedido_cantidad CHECK (cantidad > 0),
        CONSTRAINT CK_detalle_pedido_precio CHECK (precio_unitario >= 0)
);

CREATE TABLE IF NOT EXISTS pagos (
        id_pago uuid NOT NULL CONSTRAINT DF_pagos_id DEFAULT gen_random_uuid(),
        id_pedido uuid NOT NULL,
        metodo_pago VARCHAR(30) NULL,
        monto numeric(10,2) NOT NULL,
        fecha_pago timestamp(0) NOT NULL CONSTRAINT DF_pagos_fecha DEFAULT (now() AT TIME ZONE 'utc'),
        estado_pago VARCHAR(20) NOT NULL CONSTRAINT DF_pagos_estado DEFAULT ('PENDIENTE'),

        CONSTRAINT PK_pagos PRIMARY KEY (id_pago),
        CONSTRAINT FK_pago_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
        CONSTRAINT CK_pagos_metodo CHECK (
            metodo_pago IS NULL OR metodo_pago IN (
                'EFECTIVO', 'TARJETA', 'YAPE', 'PLIN', 'TRANSFERENCIA', 'OTRO'
            )
        ),
        CONSTRAINT CK_pagos_estado CHECK (estado_pago IN (
            'PENDIENTE', 'PAGADO', 'RECHAZADO', 'ANULADO'
        )),
        CONSTRAINT CK_pagos_monto CHECK (monto >= 0)
);

CREATE TABLE IF NOT EXISTS mesas (
        id_mesa integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        numero_mesa VARCHAR(10) NOT NULL,
        zona VARCHAR(30) NOT NULL,
        capacidad integer NOT NULL,
        estado_mesa VARCHAR(20) NOT NULL CONSTRAINT DF_mesas_estado DEFAULT ('DISPONIBLE'),

        CONSTRAINT PK_mesas PRIMARY KEY (id_mesa),
        CONSTRAINT UQ_mesas_numero UNIQUE (numero_mesa),
        CONSTRAINT CK_mesas_zona CHECK (zona IN ('SALON', 'TERRAZA', 'BARRA')),
        CONSTRAINT CK_mesas_estado CHECK (estado_mesa IN (
            'DISPONIBLE', 'OCUPADA', 'RESERVADA', 'MANTENIMIENTO'
        ))
);

CREATE TABLE IF NOT EXISTS payers (
        id_payer uuid NOT NULL CONSTRAINT DF_payers_id DEFAULT gen_random_uuid(),
        id_lead uuid NOT NULL,
        id_pago uuid NOT NULL,
        id_personal_cajero integer NULL,
        fecha_activacion_servicio timestamp(0) NOT NULL
            CONSTRAINT DF_payers_fecha_activacion DEFAULT (now() AT TIME ZONE 'utc'),

        CONSTRAINT PK_payers PRIMARY KEY (id_payer),
        CONSTRAINT UQ_payers_lead UNIQUE (id_lead),
        CONSTRAINT UQ_payers_pago UNIQUE (id_pago),
        CONSTRAINT FK_payers_lead FOREIGN KEY (id_lead) REFERENCES leads(id_lead),
        CONSTRAINT FK_payers_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
        CONSTRAINT FK_payers_personal FOREIGN KEY (id_personal_cajero) REFERENCES personal(id_personal)
);

CREATE TABLE IF NOT EXISTS instrucciones_pago (
        id_instruccion uuid NOT NULL CONSTRAINT DF_instrucciones_id DEFAULT gen_random_uuid(),
        id_pedido uuid NOT NULL,
        canal_pago VARCHAR(30) NOT NULL,
        monto_informado numeric(10,2) NOT NULL,
        fecha_envio timestamp(0) NOT NULL CONSTRAINT DF_instrucciones_fecha DEFAULT (now() AT TIME ZONE 'utc'),

        CONSTRAINT PK_instrucciones_pago PRIMARY KEY (id_instruccion),
        CONSTRAINT FK_instrucciones_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
        CONSTRAINT CK_instrucciones_canal CHECK (canal_pago IN (
            'EFECTIVO', 'TARJETA', 'YAPE', 'PLIN', 'TRANSFERENCIA', 'OTRO'
        )),
        CONSTRAINT CK_instrucciones_monto CHECK (monto_informado >= 0)
);

CREATE TABLE IF NOT EXISTS comprobante (
        id_comprobante uuid NOT NULL CONSTRAINT DF_comprobante_id DEFAULT gen_random_uuid(),
        id_pago uuid NOT NULL,
        tipo_comprobante VARCHAR(30) NOT NULL,
        numero_documento_cliente VARCHAR(20) NULL,
        razon_social_cliente varchar(150) NULL,
        serie VARCHAR(10) NULL,
        numero_correlativo integer NULL,
        fecha_emision timestamp(0) NULL,
        emitido boolean NOT NULL CONSTRAINT DF_comprobante_emitido DEFAULT false,

        CONSTRAINT PK_comprobante PRIMARY KEY (id_comprobante),
        CONSTRAINT UQ_comprobante_pago UNIQUE (id_pago),
        CONSTRAINT UQ_comprobante_serie_numero UNIQUE (serie, numero_correlativo),
        CONSTRAINT FK_comprobante_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago),
        CONSTRAINT CK_comprobante_tipo CHECK (tipo_comprobante IN (
            'BOLETA_DNI', 'BOLETA_SIMPLE', 'FACTURA_RUC'
        )),
        CONSTRAINT CK_comprobante_ruc CHECK (
            tipo_comprobante <> 'FACTURA_RUC'
            OR (numero_documento_cliente IS NOT NULL AND razon_social_cliente IS NOT NULL)
        ),
        CONSTRAINT CK_comprobante_fecha CHECK (
            emitido = false OR fecha_emision IS NOT NULL
        )
);

CREATE TABLE IF NOT EXISTS servicios (
        id_servicio uuid NOT NULL CONSTRAINT DF_servicios_id DEFAULT gen_random_uuid(),
        id_lead uuid NOT NULL,
        id_payer uuid NULL,
        id_mesa integer NOT NULL,
        tipo_servicio VARCHAR(30) NOT NULL CONSTRAINT DF_servicios_tipo DEFAULT ('SALON'),
        estado_servicio VARCHAR(30) NOT NULL CONSTRAINT DF_servicios_estado DEFAULT ('EN_PREPARACION'),
        responsable_atencion varchar(100) NULL,
        fecha_inicio_servicio timestamp(0) NOT NULL CONSTRAINT DF_servicios_inicio DEFAULT (now() AT TIME ZONE 'utc'),
        fecha_fin_servicio timestamp(0) NULL,

        CONSTRAINT PK_servicios PRIMARY KEY (id_servicio),
        CONSTRAINT FK_servicios_lead FOREIGN KEY (id_lead) REFERENCES leads(id_lead),
        CONSTRAINT FK_servicios_payer FOREIGN KEY (id_payer) REFERENCES payers(id_payer),
        CONSTRAINT FK_servicios_mesa FOREIGN KEY (id_mesa) REFERENCES mesas(id_mesa),
        CONSTRAINT CK_servicios_tipo CHECK (tipo_servicio = 'SALON'),
        CONSTRAINT CK_servicios_estado CHECK (estado_servicio IN (
            'EN_PREPARACION', 'SERVIDO', 'EN_CONSUMO', 'CUENTA_SOLICITADA',
            'FINALIZADO', 'CON_INCIDENCIA'
        )),
        CONSTRAINT CK_servicios_fechas CHECK (
            fecha_fin_servicio IS NULL OR fecha_fin_servicio >= fecha_inicio_servicio
        )
);

CREATE TABLE IF NOT EXISTS servicio_detalle (
        id_detalle uuid NOT NULL CONSTRAINT DF_sdet_id DEFAULT gen_random_uuid(),
        id_servicio uuid NOT NULL,
        id_producto integer NOT NULL,
        cantidad integer NOT NULL CONSTRAINT DF_sdet_cant DEFAULT (1),
        hora_pedido timestamp(0) NOT NULL CONSTRAINT DF_sdet_pedido DEFAULT (now() AT TIME ZONE 'utc'),
        hora_entrega_cocina timestamp(0) NULL,
        estado_item VARCHAR(20) NOT NULL CONSTRAINT DF_sdet_estado DEFAULT ('PENDIENTE'),

        CONSTRAINT PK_servicio_detalle PRIMARY KEY (id_detalle),
        CONSTRAINT FK_sdet_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio),
        CONSTRAINT FK_sdet_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
        CONSTRAINT CK_sdet_estado CHECK (estado_item IN ('PENDIENTE', 'EN_COCINA', 'SERVIDO', 'DEVUELTO'))
);

CREATE TABLE IF NOT EXISTS alertas_consumo (
        id_alerta uuid NOT NULL CONSTRAINT DF_alcon_id DEFAULT gen_random_uuid(),
        id_servicio uuid NOT NULL,
        tipo_alerta VARCHAR(30) NOT NULL,
        id_producto_sugerido integer NULL,
        mensaje_enviado varchar(255) NOT NULL,
        fecha_envio timestamp(0) NOT NULL CONSTRAINT DF_alcon_fecha DEFAULT (now() AT TIME ZONE 'utc'),
        aceptada boolean NULL,

        CONSTRAINT PK_alertas_consumo PRIMARY KEY (id_alerta),
        CONSTRAINT FK_alcon_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio),
        CONSTRAINT FK_alcon_producto FOREIGN KEY (id_producto_sugerido) REFERENCES productos(id_producto),
        CONSTRAINT CK_alcon_tipo CHECK (tipo_alerta IN (
            'SUGERENCIA_POSTRE', 'SUGERENCIA_BEBIDA', 'RECORDATORIO_CUENTA'
        ))
);

CREATE TABLE IF NOT EXISTS incidencias_servicio (
        id_incidencia uuid NOT NULL CONSTRAINT DF_inc_id DEFAULT gen_random_uuid(),
        id_servicio uuid NOT NULL,
        tipo_incidencia VARCHAR(30) NOT NULL,
        descripcion varchar(500) NOT NULL,
        fecha_registro timestamp(0) NOT NULL CONSTRAINT DF_inc_reg DEFAULT (now() AT TIME ZONE 'utc'),
        resuelta boolean NOT NULL CONSTRAINT DF_inc_res DEFAULT false,
        fecha_resolucion timestamp(0) NULL,

        CONSTRAINT PK_incidencias_servicio PRIMARY KEY (id_incidencia),
        CONSTRAINT FK_inc_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio),
        CONSTRAINT CK_inc_tipo CHECK (tipo_incidencia IN ('DEMORA', 'PLATO_INCORRECTO', 'QUEJA_CALIDAD', 'OTRO')),
        CONSTRAINT CK_inc_fechas CHECK (
            fecha_resolucion IS NULL OR fecha_resolucion >= fecha_registro
        )
);

CREATE TABLE IF NOT EXISTS resenas_servicio (
        id_resena uuid NOT NULL CONSTRAINT DF_resena_id DEFAULT gen_random_uuid(),
        id_servicio uuid NOT NULL,
        id_lead uuid NOT NULL,
        calificacion_estrellas smallint NOT NULL,
        comentario varchar(500) NULL,
        fecha_resena timestamp(0) NOT NULL CONSTRAINT DF_resena_fecha DEFAULT (now() AT TIME ZONE 'utc'),

        CONSTRAINT PK_resenas_servicio PRIMARY KEY (id_resena),
        CONSTRAINT UQ_resenas_servicio UNIQUE (id_servicio),
        CONSTRAINT FK_resenas_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio),
        CONSTRAINT FK_resenas_lead FOREIGN KEY (id_lead) REFERENCES leads(id_lead),
        CONSTRAINT CK_resenas_estrellas CHECK (calificacion_estrellas BETWEEN 1 AND 5)
);

CREATE TABLE IF NOT EXISTS clientes_fichados_recuperacion (
        id_fichado uuid NOT NULL CONSTRAINT DF_fich_id DEFAULT gen_random_uuid(),
        id_resena uuid NOT NULL,
        id_lead uuid NOT NULL,
        estrellas_obtenidas smallint NOT NULL,
        motivo_fichaje VARCHAR(50) NOT NULL CONSTRAINT DF_fich_motivo DEFAULT ('CALIFICACION_BAJA'),
        codigo_cupon_descuento VARCHAR(30) NOT NULL,
        porcentaje_descuento numeric(5,2) NOT NULL CONSTRAINT DF_fich_desc DEFAULT (20.00),
        estado_gestion VARCHAR(30) NOT NULL CONSTRAINT DF_fich_estado DEFAULT ('FICHADO_PENDIENTE'),
        fecha_fichaje timestamp(0) NOT NULL CONSTRAINT DF_fich_fecha DEFAULT (now() AT TIME ZONE 'utc'),
        fecha_contacto timestamp(0) NULL,

        CONSTRAINT PK_clientes_fichados PRIMARY KEY (id_fichado),
        CONSTRAINT UQ_fichados_resena UNIQUE (id_resena),
        CONSTRAINT UQ_fichados_cupon UNIQUE (codigo_cupon_descuento),
        CONSTRAINT FK_fichados_resena FOREIGN KEY (id_resena) REFERENCES resenas_servicio(id_resena),
        CONSTRAINT FK_fichados_lead FOREIGN KEY (id_lead) REFERENCES leads(id_lead),
        CONSTRAINT CK_fichados_estado CHECK (estado_gestion IN (
            'FICHADO_PENDIENTE', 'CUPON_ENVIADO', 'CANJEADO', 'EXPIRADO'
        )),
        CONSTRAINT CK_fichados_descuento CHECK (
            porcentaje_descuento > 0 AND porcentaje_descuento <= 100
        )
);

